#!/usr/bin/env python3
"""Convert the Bluetooth SIG company_identifiers.yaml into VIGIL's compact asset.

usage: sig2tsv.py <company_identifiers.yaml> <out.tsv> <retrieved-date>
One line per company: 4 hex digits, a tab, a display name with the corporate
suffix trimmed ("Apple, Inc." -> "Apple"). No YAML library needed: the file is a
flat list of value/name pairs.
"""
import re, sys

SUFFIX = re.compile(
    r"[,\s]+(inc|incorporated|ltd|limited|llc|l\.l\.c|corp|corporation|co|company|gmbh|ag|"
    r"b\.v|bv|s\.a|sa|s\.r\.l|srl|s\.p\.a|spa|oy|ab|a/s|as|aps|pte|pty|plc|kg|"
    r"co\.,?\s*ltd|gmbh\s*&\s*co\.?\s*kg|k\.k|kk|n\.v|nv|s\.l|sl|sas|s\.a\.s|limited liability company)\.?$",
    re.I,
)

def tidy(name: str) -> str:
    name = re.sub(r"\s+", " ", name).strip()
    for _ in range(3):  # "Foo Co., Ltd." needs more than one pass
        new = SUFFIX.sub("", name).strip(" ,")
        if new == name or len(new) < 2:
            break
        name = new
    return name

def main() -> None:
    src, out, date = sys.argv[1], sys.argv[2], sys.argv[3]
    rows, value = {}, None
    for line in open(src, encoding="utf-8"):
        m = re.match(r"\s*-\s*value:\s*0x([0-9A-Fa-f]{4})\s*$", line)
        if m:
            value = int(m.group(1), 16)
            continue
        m = re.match(r"\s*name:\s*(.*?)\s*$", line)
        if m and value is not None:
            raw = m.group(1)
            if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "'\"":
                q = raw[0]
                raw = raw[1:-1]
                raw = raw.replace("''", "'") if q == "'" else raw.replace('\\"', '"')
            name = tidy(raw.replace("\t", " "))
            if name:
                rows[value] = name
            value = None
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Bluetooth SIG Assigned Numbers: company identifiers (company_identifiers.yaml), retrieved %s.\n" % date)
        f.write("# Generated by tools/sig2tsv.py; corporate suffixes trimmed for display. Format: HEX<TAB>name\n")
        for v in sorted(rows):
            f.write("%04X\t%s\n" % (v, rows[v]))
    print(len(rows), "companies")

main()
